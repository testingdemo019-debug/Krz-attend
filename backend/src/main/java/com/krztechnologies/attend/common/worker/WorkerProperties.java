package com.krztechnologies.attend.common.worker;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import java.net.URI;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.validation.annotation.Validated;

/**
 * The recognition worker (WORKER_* in deploy/.env): its internal API and the ID under which it writes its heartbeat.
 * The token is sent as {@code X-Worker-Token}; {@link #toString()} leaves it out so it can never reach a log.
 *
 * @param id WORKER_ID, the heartbeat key is {@code krz:hb:worker:<id>}
 * @param url WORKER_API_URL (containers: http://worker:8090; the dev profile on the host: http://localhost:8090)
 * @param token WORKER_API_TOKEN, generated by deploy/scripts/init-env
 */
@Validated
@ConfigurationProperties("krz.worker")
public record WorkerProperties(
        @NotBlank String id, @NotNull URI url, @NotBlank String token) {

    @Override
    public String toString() {
        return "WorkerProperties[id=" + id + ", url=" + url + "]";
    }
}
