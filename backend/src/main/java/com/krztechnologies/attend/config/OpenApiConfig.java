package com.krztechnologies.attend.config;

import com.krztechnologies.attend.common.app.AppProperties;
import com.krztechnologies.attend.common.security.Permission;
import com.krztechnologies.attend.common.security.PublicEndpoint;
import com.krztechnologies.attend.common.security.RequiresPermission;
import com.krztechnologies.attend.common.security.SignedIn;
import io.swagger.v3.core.converter.AnnotatedType;
import io.swagger.v3.core.converter.ModelConverter;
import io.swagger.v3.core.converter.ModelConverterContext;
import io.swagger.v3.core.util.Json;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.servers.Server;
import java.lang.reflect.RecordComponent;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Iterator;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;
import org.jspecify.annotations.Nullable;
import org.springdoc.core.customizers.OperationCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * The OpenAPI document ({@code docs/api/openapi.json}, generated by OpenApiExportTest). Every operation carries
 * {@code x-permission}: the permission keys joined with {@code +} (all needed) or {@code |} (any one), or
 * {@code signed-in}, {@code signed-in:no-access} or {@code public}. The permission-matrix test reads it.
 *
 * <p>Response and request records are exact (D-083): every component is required, because Jackson writes each one
 * (null included), and a component annotated with JSpecify's {@code @Nullable} is typed "T or null". The frontend's
 * generated types follow, so it neither guards fields that are always there nor forgets the ones that can be null.
 *
 * <p>A type nested in another class is named {@code Outer.Inner} ({@code EnrolmentViews.PersonRef}): simple names
 * repeat across modules, and two types with one name would silently share one schema (D-085).
 */
@Configuration(proxyBeanMethods = false)
public class OpenApiConfig {

    public static final String EXTENSION = "x-permission";
    private static final String BASE_PACKAGE = "com.krztechnologies.attend.";

    @Bean
    OpenAPI krzAttendOpenApi(AppProperties app) {
        return new OpenAPI()
                .info(new Info()
                        .title("KRZ Attend API")
                        .version(app.version())
                        .description("Contract between the KRZ Attend backend and frontend (base path /api/v1)."))
                // Same origin (nginx, or the Vite proxy in development); fixed so the exported file is stable.
                .servers(List.of(new Server().url("/")));
    }

    @Bean
    OperationCustomizer permissionExtension() {
        return (operation, handler) -> {
            RequiresPermission required = handler.getMethodAnnotation(RequiresPermission.class);
            SignedIn signedIn = handler.getMethodAnnotation(SignedIn.class);
            String value;
            if (required != null) {
                value = Arrays.stream(required.value())
                        .map(Permission::key)
                        .collect(Collectors.joining(required.anyOf() ? "|" : "+"));
            } else if (signedIn != null) {
                value = signedIn.requireAccess() ? "signed-in" : "signed-in:no-access";
            } else if (handler.hasMethodAnnotation(PublicEndpoint.class)) {
                value = "public";
            } else {
                value = "none";
            }
            operation.addExtension(EXTENSION, value);
            return operation;
        };
    }

    @Bean
    ModelConverter recordNullability() {
        return new ModelConverter() {
            @Override
            public @Nullable Schema<?> resolve(
                    AnnotatedType type, ModelConverterContext context, Iterator<ModelConverter> chain) {
                Class<?> raw = Json.mapper().constructType(type.getType()).getRawClass();
                Class<?> outer = raw.getEnclosingClass();
                if ((type.getName() == null || type.getName().isBlank())
                        && outer != null
                        && raw.getName().startsWith(BASE_PACKAGE)) {
                    type.name(outer.getSimpleName() + "." + raw.getSimpleName());
                }
                Schema<?> resolved = chain.hasNext() ? chain.next().resolve(type, context, chain) : null;
                if (resolved == null || !raw.isRecord()) {
                    return resolved;
                }
                Schema<?> model = resolved.get$ref() == null
                        ? resolved
                        : context.getDefinedModels()
                                .get(resolved.get$ref()
                                        .substring(resolved.get$ref().lastIndexOf('/') + 1));
                if (model != null && model.getProperties() != null) {
                    describe(raw, model);
                }
                return resolved;
            }
        };
    }

    private static void describe(Class<?> record, Schema<?> model) {
        @SuppressWarnings("rawtypes")
        Map<String, Schema> properties = model.getProperties();
        List<String> required = new ArrayList<>();
        for (RecordComponent component : record.getRecordComponents()) {
            Schema<?> property = properties.get(component.getName());
            if (property == null) {
                continue;
            }
            required.add(component.getName());
            if (component.getAnnotatedType().isAnnotationPresent(Nullable.class)) {
                properties.put(component.getName(), orNull(property));
            }
        }
        model.setRequired(required);
    }

    /** OpenAPI 3.1: "null" joins the property's types; a reference becomes anyOf(reference, null). */
    private static Schema<?> orNull(Schema<?> property) {
        if (property.get$ref() != null) {
            Schema<Object> union = new Schema<>();
            union.setAnyOf(List.of(property, new Schema<>().types(Set.of("null"))));
            return union;
        }
        Set<String> types = new LinkedHashSet<>();
        if (property.getTypes() != null) {
            types.addAll(property.getTypes());
        } else if (property.getType() != null) {
            types.add(property.getType());
        }
        types.add("null");
        property.setTypes(types);
        return property;
    }
}
