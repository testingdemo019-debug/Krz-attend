import { useEffect, useState } from 'react';

/** The current time, refreshed every `everyMs` (renders stay pure; clocks and "now" markers still move). */
export function useNow(everyMs: number): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const timer = setInterval(() => {
      setNow(Date.now());
    }, everyMs);
    return () => {
      clearInterval(timer);
    };
  }, [everyMs]);
  return now;
}
