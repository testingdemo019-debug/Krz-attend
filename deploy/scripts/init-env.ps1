# Creates deploy/.env from .env.example (only if it is missing) and generates the random secrets
# that are still blank. Existing values are never changed and no value is ever printed.
# Usage: powershell -ExecutionPolicy Bypass -File deploy\scripts\init-env.ps1 [--help]
param([Parameter(ValueFromRemainingArguments = $true)][string[]]$CliArgs)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'lib\env.ps1')

$opts = ConvertFrom-KrzCliArgs -CliArgs $CliArgs -Known @('help')
if ($opts.ContainsKey('help')) {
    @'
init-env - create deploy/.env and generate the random secrets (idempotent, prints no values).
Generated when blank: ENCRYPTION_KEY_<active id>, REDIS_BACKEND_PASSWORD, REDIS_WORKER_PASSWORD,
REDIS_HEALTH_PASSWORD, WORKER_API_TOKEN, GO2RTC_API_PASSWORD.
The DB passwords are generated by database/bootstrap/run_bootstrap; ENTRA_CLIENT_SECRET and
CAMERA_01_PASSWORD are typed into deploy/.env by you.
'@
    exit 0
}

$envPath = Get-KrzEnvPath
$examplePath = Join-Path (Split-Path $envPath) '.env.example'
if (-not (Test-Path -LiteralPath $envPath)) {
    Copy-Item -LiteralPath $examplePath -Destination $envPath
    Write-Output 'Created deploy/.env from .env.example.'
}
Protect-KrzSecretFile -Path $envPath

$activeKeyId = Get-KrzEnvValue -Path $envPath -Key 'ENCRYPTION_ACTIVE_KEY_ID' -Default 'k1'
$generated = [ordered]@{
    "ENCRYPTION_KEY_$activeKeyId" = { New-KrzSecret -Bytes 32 -Format base64 }
    'REDIS_BACKEND_PASSWORD'      = { New-KrzSecret -Bytes 32 }
    'REDIS_WORKER_PASSWORD'       = { New-KrzSecret -Bytes 32 }
    'REDIS_HEALTH_PASSWORD'       = { New-KrzSecret -Bytes 32 }
    'WORKER_API_TOKEN'            = { New-KrzSecret -Bytes 48 }
    'GO2RTC_API_PASSWORD'         = { New-KrzSecret -Bytes 32 }
}
foreach ($key in $generated.Keys) {
    if ((Get-KrzEnvValue -Path $envPath -Key $key) -eq '') {
        Set-KrzEnvValue -Path $envPath -Key $key -Value (& $generated[$key])
        Write-Output "Generated $key."
    } else {
        Write-Output "Kept existing $key."
    }
}
Protect-KrzSecretFile -Path $envPath

$userOwned = @('ENTRA_CLIENT_SECRET', 'ENTRA_CLIENT_SECRET_EXPIRES', 'BOOTSTRAP_ADMIN_EMAILS', 'MAIL_TEST_RECIPIENT', 'CAMERA_01_USERNAME', 'CAMERA_01_PASSWORD')
$blank = @($userOwned | Where-Object { (Get-KrzEnvValue -Path $envPath -Key $_) -eq '' })
if ($blank.Count -gt 0) { Write-Output ("Still to be filled in by you (edit deploy/.env): " + ($blank -join ', ')) }
Write-Output 'deploy/.env is readable only by the current user.'
