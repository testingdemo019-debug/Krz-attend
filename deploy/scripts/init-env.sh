#!/usr/bin/env bash
# Creates deploy/.env from .env.example (only if it is missing) and generates the random secrets
# that are still blank. Existing values are never changed and no value is ever printed.
set -euo pipefail
# shellcheck source=lib/env.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/env.sh"

for arg in "$@"; do
  case "$arg" in
    --help|-h)
      cat <<'EOF'
init-env - create deploy/.env and generate the random secrets (idempotent, prints no values).
Generated when blank: ENCRYPTION_KEY_<active id>, REDIS_BACKEND_PASSWORD, REDIS_WORKER_PASSWORD,
REDIS_HEALTH_PASSWORD, WORKER_API_TOKEN, GO2RTC_API_PASSWORD.
The DB passwords are generated by database/bootstrap/run_bootstrap.sh; ENTRA_CLIENT_SECRET and
CAMERA_01_PASSWORD are typed into deploy/.env by you.
EOF
      exit 0 ;;
    *) echo "Unknown option '$arg'. Use --help." >&2; exit 2 ;;
  esac
done

umask 077
ENV_FILE="$(krz_env_path)"
EXAMPLE_FILE="$(dirname "$ENV_FILE")/.env.example"
if [[ ! -f "$ENV_FILE" ]]; then
  cp "$EXAMPLE_FILE" "$ENV_FILE"
  echo "Created deploy/.env from .env.example."
fi
chmod 600 "$ENV_FILE"

active_key_id="$(krz_env_get "$ENV_FILE" ENCRYPTION_ACTIVE_KEY_ID k1)"
generate() { # key bytes format
  if [[ -z "$(krz_env_get "$ENV_FILE" "$1")" ]]; then
    krz_env_set "$ENV_FILE" "$1" "$(krz_secret "$2" "$3")"
    echo "Generated $1."
  else
    echo "Kept existing $1."
  fi
}
generate "ENCRYPTION_KEY_${active_key_id}" 32 base64
generate REDIS_BACKEND_PASSWORD 32 urlsafe
generate REDIS_WORKER_PASSWORD 32 urlsafe
generate REDIS_HEALTH_PASSWORD 32 urlsafe
generate WORKER_API_TOKEN 48 urlsafe
generate GO2RTC_API_PASSWORD 32 urlsafe
chmod 600 "$ENV_FILE"

blank=()
for key in ENTRA_CLIENT_SECRET ENTRA_CLIENT_SECRET_EXPIRES BOOTSTRAP_ADMIN_EMAILS MAIL_TEST_RECIPIENT CAMERA_01_USERNAME CAMERA_01_PASSWORD; do
  [[ -z "$(krz_env_get "$ENV_FILE" "$key")" ]] && blank+=("$key")
done
if [[ ${#blank[@]} -gt 0 ]]; then echo "Still to be filled in by you (edit deploy/.env): ${blank[*]}"; fi
echo "deploy/.env has mode 600."
